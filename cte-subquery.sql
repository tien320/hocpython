GROUP BY GENREID 
)
SELECT t.GENREID ,t.ALBUMID ,t.NAME ,t.UNITPRICE   FROM TRACK t 
JOIN genreavgprice g ON g.GENREID = t.GENREID 
WHERE t.UNITPRICE > g.AVG ;
