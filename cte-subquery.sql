WITH albumstat AS ( 
SELECT ALBUMID ,avg(UNITPRICE ) AS avgalb FROM track
WHERE ALBUMID IS NOT NULL 
GROUP BY ALBUMID 
)
SELECT t.TRACKID ,t.NAME ,ast.AVGALB   FROM TRACK t 
JOIN albumstat ast ON ast.ALBUMID = t.ALBUMID 
FETCH FIRST 10 ROWS ONLY;
