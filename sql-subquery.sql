SELECT 
t.TRACKID ,t.NAME AS track_name,m.NAME AS mediatype_name,g.NAME AS genre_name
FROM track t
INNER JOIN MEDIATYPE m 
ON t.MEDIATYPEID = m.MEDIATYPEID 
INNER JOIN GENRE g 
ON g.GENREID = t.GENREID
WHERE m.NAME  LIKE '%MPEG%';
