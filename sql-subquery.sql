SELECT 
g.GENREID ,g.NAME AS genre_name , count(t.TRACKID ) AS total_track
FROM genre g
LEFT JOIN TRACK t 
ON g.GENREID = t.GENREID
GROUP BY g.GENREID , g.NAME 
ORDER BY TOTAL_TRACK DESC, g.NAME ASC;
