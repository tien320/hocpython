c.CUSTOMERID ,c.FIRSTNAME ,c.LASTNAME ,c.COUNTRY 
FROM CUSTOMER c 
WHERE c.COUNTRY in (
SELECT distinct e.COUNTRY 
FROM EMPLOYEE e 
