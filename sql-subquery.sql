SELECT 
g.GENREID ,g.NAME 
FROM GENRE g 
WHERE EXISTS (
SELECT 1 
FROM track t
INNER JOIN INVOICELINE il ON il.TRACKID = t.TRACKID 
WHERE t.GENREID = g.GENREID 
)
ORDER BY g.GENREID ;
